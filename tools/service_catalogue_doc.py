"""Write docs/service-catalogue.md from the catalogue data.

uv run python tools/service_catalogue_doc.py
"""

import pathlib

from astemia.catalogue import load_catalogue, load_crosswalk

OUT = pathlib.Path(__file__).parents[1] / "docs" / "service-catalogue.md"


def main() -> None:
    cat = load_catalogue()
    groups = cat["groups"]
    spec = [g for g in groups if g["source"] == "ams-002-annex-a15"]
    ext = [g for g in groups if g["source"] == "astemia-extension"]
    n_spec = sum(len(g["services"]) for g in spec)
    n_ext = sum(len(g["services"]) for g in ext)
    lines = [
        "# Hospital service catalogue (generated)",
        "",
        f"Catalogue version {cat['version']}. Generated by `tools/service_catalogue_doc.py` from",
        "`src/astemia/catalogue/data/service_catalogue.json`. Do not edit by hand.",
        "",
        f"* **D01-D36** ({len(spec)} groups, {n_spec} services) are the department groups of",
        "  AMS-002 Annex A15, which assigns every listing of",
        f"  {cat['coverage_template']}",
        "  to one primary group. Services found only in directory B were added to these",
        "  groups where they belong.",
        f"* **D37-D{len(groups):02d}** ({len(ext)} groups, {n_ext} services) are ASTEMIA extension",
        "  groups: services a comprehensive general hospital and the Nigeria country profile",
        "  need, and D50 for the non-clinical patient, family and visitor support listings.",
        "  All of them are confirmed in pilot scope (23 November 2026).",
        "",
        "Pilot scope does not switch a service on: each one is still activated per facility",
        "with a named owner and an approval reference (CAT-05).",
        "",
        "Both public directories are crosswalked listing by listing to a service (appendices",
        "below), and tests fail if any listing is unmapped. Listing names become search",
        "aliases when a tenant provisions the catalogue.",
        "",
        "Every service is a template. A tenant provisions it as a draft",
        "(`POST /v1/control/catalogue/provision`) and activates it per facility with a named",
        "owner and approval reference (`POST /v1/control/services/{id}/activate`).",
        "",
        "Care settings: E emergency, I inpatient, O outpatient, D day case, C community,",
        "V virtual, X diagnostic, S support.",
        "",
    ]
    abbrev = {
        "emergency": "E",
        "inpatient": "I",
        "outpatient": "O",
        "day_case": "D",
        "community": "C",
        "virtual": "V",
        "diagnostic": "X",
        "support": "S",
    }
    division = None
    for g in groups:
        if g["division"] != division:
            division = g["division"]
            lines += [f"## {division}", ""]
        tag = " *(ASTEMIA extension)*" if g["source"] == "astemia-extension" else ""
        lines += [f"### {g['code']} {g['name']}{tag}", ""]
        lines += [f"**Workflow** {g['workflow']} {', '.join(g['requirement_refs'])}", ""]
        lines += [f"**Canonical records** {', '.join(g['canonical_records'])}", ""]
        lines += [f"**Security checks** {g['security_checks']}", ""]
        lines += [f"**Acceptance** {g['acceptance']}", ""]
        if g["directory_a_positions"]:
            positions = ", ".join(map(str, g["directory_a_positions"]))
            lines += [f"**Directory A positions** {positions}", ""]
        lines += ["| Code | Service | Ages | Settings |", "|---|---|---|---|"]
        for s in g["services"]:
            settings = " ".join(abbrev[c] for c in s["care_settings"])
            lines.append(f"| {s['code']} | {s['name']} | {s['age_policy']} | {settings} |")
        lines.append("")
    names = {s["code"]: s["name"] for g in groups for s in g["services"]}
    for key in ("directory_a", "directory_b"):
        cw = load_crosswalk(key)
        lines += [
            f"## Appendix: {cw['title']} crosswalk",
            "",
            f"Source {cw['source']}, snapshot {cw['snapshot']}, {len(cw['entries'])} listings.",
            "",
            "| # | Listing | Service |",
            "|---|---|---|",
        ]
        for e in cw["entries"]:
            listing = e["listing"].replace("|", "/")
            code = e["service_code"]
            lines.append(f"| {e['position']} | {listing} | {code} {names[code]} |")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
